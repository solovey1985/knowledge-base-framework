import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');

async function collectIcons(relativePath) {
  const absolute = path.join(root, relativePath);
  const entries = await readdir(absolute, { withFileTypes: true });
  const icons = new Set();
  for (const entry of entries) {
    const file = path.join(relativePath, entry.name);
    if (entry.isDirectory()) {
      for (const icon of await collectIcons(file)) icons.add(icon);
    } else if (/\.(tsx?|hbs)$/.test(entry.name)) {
      const source = await readFile(path.join(root, file), 'utf8');
      for (const icon of source.matchAll(/icon-\[lucide--[a-z0-9-]+\]/g)) icons.add(icon[0]);
    }
  }
  return icons;
}

async function writeStyles(output, directories, files = []) {
  const icons = new Set();
  for (const directory of directories) {
    for (const icon of await collectIcons(directory)) icons.add(icon);
  }
  for (const file of files) {
    const source = await readFile(path.join(root, file), 'utf8');
    for (const icon of source.matchAll(/icon-\[lucide--[a-z0-9-]+\]/g)) icons.add(icon[0]);
  }
  // Scan only icon candidates. Scanning all utilities again would override responsive core styles.
  const css = [
    '/* Generated by scripts/build-icon-styles.mjs. Edit icon classes at their call sites. */',
    '@import "tailwindcss/utilities" layer(utilities) source(none);',
    '@plugin "@iconify/tailwind4";',
    ...[...icons].sort().map(icon => `@source inline("${icon}");`),
    '',
  ].join('\n');
  await writeFile(path.join(root, output), css);
}

await writeStyles('client/styles/icons-core.css', ['templates/default', 'client/shared'], ['client/search.ts']);
for (const name of ['work-manager', 'interview-prep', 'tech-memory', 'three-d-viewer']) {
  await writeStyles(`client/plugins/${name}/icons.css`, [`client/plugins/${name}`]);
}
